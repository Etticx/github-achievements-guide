"""Build the site's HTML pages and sitemap.xml.

Run from the repo root after adding a badge or changing a title/description:
    python scripts/build_pages.py

The guide text itself lives in docs/achievements/*.md and is loaded by assets/site.js,
so editing a guide does not need a rebuild.
"""
from datetime import date
from html import escape
from pathlib import Path

SITE = "https://etticx.github.io/github-achievements-guide/"
REPO = "https://github.com/Etticx/github-achievements-guide"
ROOT = Path(__file__).resolve().parent.parent

HOME = {
    "title": "How to Get Every GitHub Achievement · Step-by-Step Guide",
    "description": "Step-by-step guides for every GitHub achievement: Pull Shark, YOLO, "
                   "Quickdraw, Pair Extraordinaire, Starstruck, Galaxy Brain and Public "
                   "Sponsor. Do it on github.com or with git and the gh CLI.",
}

# Order matches the cards on the home page (assets/site.js).
BADGES = {
    "quickdraw": ("Quickdraw", "Close an issue or pull request within 5 minutes of opening it. Takes about a minute on github.com or with two gh commands."),
    "yolo": ("YOLO", "Merge a pull request without a code review. Why you need a review request first, with website and gh CLI steps."),
    "pull-shark": ("Pull Shark", "Get 2, 16, 128 or 1024 of your pull requests merged. Step-by-step on github.com or with a git + gh loop."),
    "pair-extraordinaire": ("Pair Extraordinaire", "Add a Co-authored-by line to a commit in a merged pull request. Which email to use, with website and CLI steps."),
    "galaxy-brain": ("Galaxy Brain", "Get answers accepted in GitHub Discussions. Where answers still count and how to find open questions."),
    "starstruck": ("Starstruck", "Get 16, 128, 512 or 4096 stars on a repository you own. What works, and what breaks GitHub's rules."),
    "public-sponsor": ("Public Sponsor", "Sponsor a developer through GitHub Sponsors. A one-time sponsorship is enough."),
}

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{description}">
<link rel="canonical" href="{url}">
<meta name="google-site-verification" content="-RqExHvDMYd0tGsSyvU5ADpDxqTPw8vKmkf6-Jf6XxA">
<meta property="og:type" content="website">
<meta property="og:site_name" content="GitHub Achievements Guide">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{description}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{site}assets/social-preview.png">
<meta property="og:image:width" content="1280">
<meta property="og:image:height" content="640">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="https://github.githubassets.com/images/modules/profile/achievements/pull-shark-default.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
<link rel="stylesheet" href="{base}assets/site.css">
</head>
<body data-base="{base}"{page_attr}>
<!-- Generated by scripts/build_pages.py. Edit that script, not this file. -->
<header class="site">
  <div class="wrap">
    <a class="brand" href="{home}">GitHub <span>Achievements</span> Guide</a>
    <a class="gh-link" href="{repo}">Star on GitHub</a>
  </div>
</header>

<main id="app" class="wrap">
  <noscript><p>This page needs JavaScript. You can read the guides directly on <a href="{repo}">GitHub</a>.</p></noscript>
</main>

<footer>
  <div class="wrap">
    Unofficial guide, not affiliated with or endorsed by GitHub. Badge images belong to GitHub.
    Content is <a href="{repo}/blob/main/LICENSE">MIT licensed</a>. Last checked {checked}.
  </div>
</footer>

<script src="https://cdnjs.cloudflare.com/ajax/libs/marked/12.0.2/marked.min.js"></script>
<script src="{base}assets/site.js"></script>
</body>
</html>
"""


def page(title, description, url, base, page_id=None):
    return TEMPLATE.format(
        title=escape(title), description=escape(description), url=url, site=SITE,
        base=base, home=base or "./", repo=REPO, checked="November 2026",
        page_attr=f' data-page="{page_id}"' if page_id else "",
    )


def main():
    (ROOT / "index.html").write_text(
        page(HOME["title"], HOME["description"], SITE, ""), encoding="utf-8", newline="\n")
    urls = [SITE]
    for slug, (name, desc) in BADGES.items():
        url = f"{SITE}{slug}/"
        out = ROOT / slug / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(page(f"How to Get the {name} Achievement on GitHub", desc, url, "../", slug),
                       encoding="utf-8", newline="\n")
        urls.append(url)

    today = date.today().isoformat()
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{u}</loc><lastmod>{today}</lastmod></url>\n" for u in urls)
        + "</urlset>\n", encoding="utf-8", newline="\n")
    # No robots.txt: crawlers only read it at the domain root (etticx.github.io), not under /repo/.
    print(f"Built {len(urls)} pages")


if __name__ == "__main__":
    main()
